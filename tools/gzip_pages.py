# PlatformIO pre-build step: gzips the web pages in src/web_pages.h into
# include/web_pages_gz.h. The counter sends the compressed bytes (about a
# third of the size), which loads far more reliably over a weak WiFi link and
# takes less flash. Browsers and the app's WebView unpack gzip themselves.
#
# Edit the pages in src/web_pages.h as usual; this file is regenerated on
# every build and is not committed.
import gzip
import os
import re

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:  # run by hand: python tools/gzip_pages.py
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "src", "web_pages.h")
OUT = os.path.join(ROOT, "include", "web_pages_gz.h")

PAGE = re.compile(r'static const char (\w+)\[\] PROGMEM = R"rawliteral\((.*?)\)rawliteral";', re.S)


def build():
    with open(SRC, encoding="utf-8") as f:
        text = f.read()
    pages = PAGE.findall(text)
    if not pages:
        raise SystemExit("gzip_pages: no pages found in " + SRC)
    lines = [
        "// Generated by tools/gzip_pages.py from src/web_pages.h - do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    report = []
    for name, body in pages:
        raw = body.encode("utf-8")
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        lines.append("static const uint8_t %s_GZ[] PROGMEM = {" % name)
        for i in range(0, len(gz), 20):
            lines.append("  " + ",".join(str(b) for b in gz[i:i + 20]) + ",")
        lines.append("};")
        lines.append("static const size_t %s_GZ_LEN = %d;" % (name, len(gz)))
        lines.append("")
        report.append("%s %d->%d" % (name, len(raw), len(gz)))
    out = "\n".join(lines)
    old = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            old = f.read()
    if out != old:  # unchanged pages: no rebuild of web.cpp
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
    print("gzip_pages: " + ", ".join(report))


build()
